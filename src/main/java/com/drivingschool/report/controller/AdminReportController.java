package com.drivingschool.report.controller;

import com.drivingschool.auth.annotation.RequireAdmin;
import com.drivingschool.auth.service.AuthSessionService;
import com.drivingschool.report.service.*;
import com.drivingschool.common.exception.RecordNotFoundException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.*;
import java.io.IOException;
import java.io.PrintWriter;
import java.time.Clock;
import java.time.LocalDate;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;

@Controller
@RequireAdmin
@RequestMapping("/admin/reports")
public class AdminReportController {
    // SOLID: D - The controller receives the small report interface through its constructor.
    private final ReportCatalog reports;
    private final AuthSessionService auth;
    private final Clock clock;
    private final String school;

    // Accepts the report provider chosen by Spring.
    public AdminReportController(ReportCatalog reports, AuthSessionService auth, Clock clock,
            @Value("${app.school.name:DriveSpark Academy}") String school) {
        this.reports = reports; this.auth = auth; this.clock = clock; this.school = school;
    }

    // CRUD: READ   - finds or lists report totals
    // Loads the same report rows that the CSV download will use.
    @GetMapping
    public String show(Model model, HttpServletRequest request, HttpServletResponse response) {
        response.setHeader("Cache-Control", "no-store");
        model.addAttribute("reports", reports.business());
        model.addAttribute("reportSchool", school);
        model.addAttribute("reportGenerated", generated());
        model.addAttribute("reportAdmin", auth.requireAdmin(request).getName());
        return "admin/reports";
    }

    // CRUD: READ   - finds or lists report totals
    // Writes each report row with quoted CSV cells; no files or records are changed.
    @GetMapping("/export.csv")
    public void export(HttpServletRequest request, HttpServletResponse response,
            @RequestParam(required = false) String section) throws IOException {
        String admin = auth.requireAdmin(request).getName();
        List<BusinessReportSection> sections = reports.business();
        if (section != null && !section.isBlank()) {
            sections = sections.stream().filter(s -> s.key().equals(section)).toList();
            if (sections.isEmpty()) throw new RecordNotFoundException("That report section is unavailable. Return to reports and choose a section.");
        }
        response.setContentType("text/csv;charset=UTF-8");
        response.setHeader("Cache-Control", "no-store");
        String suffix = section == null || section.isBlank() ? "" : "-" + sections.get(0).key();
        response.setHeader("Content-Disposition", "attachment; filename=drivespark-report-" + LocalDate.now(clock) + suffix + ".csv");
        PrintWriter writer = response.getWriter();
        writer.write('\uFEFF');
        row(writer, List.of("Driving school report"));
        row(writer, List.of(school));
        row(writer, List.of("Generated on " + generated()));
        row(writer, List.of("Generated by " + admin));
        row(writer, List.of("Reporting period: All records"));
        writer.write("\r\n");
        for (var report : sections) {
            row(writer, List.of(report.title()));
            row(writer, report.headings());
            if (report.rows().isEmpty()) row(writer, List.of("No records for this period"));
            for (var cells : report.rows()) row(writer, cells);
            writer.write("\r\n");
        }
        writer.flush();
    }

    private String generated() {
        return ZonedDateTime.now(clock).format(DateTimeFormatter.ofPattern("d MMM yyyy, h:mm a", Locale.UK))
                .replace("AM", "am").replace("PM", "pm");
    }

    private void row(PrintWriter writer, List<String> cells) {
        writer.write(cells.stream().map(this::csv).collect(java.util.stream.Collectors.joining(",")) + "\r\n");
    }

    // Protects spreadsheet cells from formula prefixes and escapes embedded quotation marks.
    private String csv(String value) {
        String safeValue = value == null ? "-" : value;
        String trimmed = safeValue.stripLeading();
        if (!trimmed.isEmpty() && "=+-@".indexOf(trimmed.charAt(0)) >= 0) safeValue = "'" + safeValue;
        return "\"" + safeValue.replace("\"", "\"\"") + "\"";
    }
}
